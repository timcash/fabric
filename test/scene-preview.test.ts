import test from 'node:test';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createScenePreview, describeSceneModel } from '../src/scene-preview.ts';

test('Full content uses the actual slide geometry/materials even when the slide root is hidden', () => {
  const source = new THREE.Group();
  source.name = 'assembly';
  source.visible = false;
  source.scale.setScalar(.001);
  const mesh = new THREE.Mesh(new THREE.BoxGeometry(6, 3, 5), new THREE.MeshStandardMaterial());
  mesh.position.y = 1.5;
  source.add(mesh);
  const preview = createScenePreview(source, new THREE.Vector3(8, 4.5, 11));
  const copy = preview.model.children[0] as THREE.Mesh;
  assert.notEqual(copy, mesh);
  assert.equal(copy.geometry, mesh.geometry);
  assert.equal(copy.material, mesh.material);
  assert.equal(preview.sharedResources, true);
  assert.deepEqual(preview.contents, describeSceneModel(source));
  assert.equal(preview.model.visible, true);
  assert.equal(preview.model.scale.x, 1);
  assert.equal(source.visible, false);
  assert.equal(source.scale.x, .001);
  const bounds = new THREE.Box3().setFromObject(preview.group);
  const size = bounds.getSize(new THREE.Vector3());
  assert.ok(bounds.min.y >= .149 && size.y > .1, '3D content sits above the tile');
  assert.ok(size.x <= 2.751 && size.z <= 2.801 && size.y <= 2.201, 'Fits in the tile content region');
  let disposed = 0;
  mesh.geometry.addEventListener('dispose', () => disposed++);
  mesh.material.addEventListener('dispose', () => disposed++);
  preview.group.clear();
  assert.equal(disposed, 0, 'Discarding a preview must not dispose Slide-mode GPU resources');
  mesh.geometry.dispose(); mesh.material.dispose();
});

test('preview children follow live animation, transforms, and visibility without inheriting root transitions', () => {
  const source = new THREE.Group();
  const nested = new THREE.Group();
  const core = new THREE.Mesh(new THREE.TorusKnotGeometry(), new THREE.MeshStandardMaterial());
  nested.add(core); source.add(nested);
  const preview = createScenePreview(source, new THREE.Vector3(8, 4.5, 11));
  nested.position.set(1, 2, 3); nested.scale.setScalar(.8);
  core.rotation.set(.2, .4, .6); core.visible = false;
  source.visible = false; source.scale.setScalar(.001);
  preview.sync();
  const copy = preview.model.children[0]!.children[0]!;
  assert.deepEqual(copy.quaternion.toArray(), core.quaternion.toArray());
  assert.deepEqual(copy.parent!.position.toArray(), nested.position.toArray());
  assert.deepEqual(copy.parent!.scale.toArray(), nested.scale.toArray());
  assert.equal(copy.visible, false);
  assert.equal(preview.model.visible, true);
  assert.equal(preview.model.scale.x, 1);
  core.visible = true; core.rotation.y += .5;
  preview.sync();
  assert.equal(copy.visible, true);
  assert.deepEqual(copy.quaternion.toArray(), core.quaternion.toArray());
  core.geometry.dispose(); core.material.dispose();
});
