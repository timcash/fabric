/**
 * Builds the offline service worker for the installed app. The app shell (this build's hashed files, the pages,
 * manifest and icons) is precached under a cache named after the build, so a new deploy replaces it cleanly. The
 * large, rarely changing assets (the MediaPipe runtime and model, the simulation mesh) are cached on first use.
 * Page loads go to the network first so a new deploy shows up, falling back to the cache when offline.
 */
export function serviceWorkerSource(files: readonly string[]): string {
  const precache = ['./', 'index.html', 'manifest.webmanifest', 'favicon.svg', 'brand/logo.svg', 'brand/icon-192.png', 'brand/icon-512.png', 'brand/maskable-512.png', 'brand/apple-touch-icon.png', ...files];
  let hash = 0;
  for (const c of precache.join('|')) hash = (hash * 31 + c.charCodeAt(0)) | 0;
  const version = (hash >>> 0).toString(36);
  return `// Generated by scripts/service-worker.ts at build time.
const SHELL = 'fabric-shell-${version}';
const RUNTIME = 'fabric-runtime-v1';
const PRECACHE = ${JSON.stringify(precache)};
const LAZY = /\\/(mediapipe|sim)\\//;

self.addEventListener('install', event => {
  event.waitUntil(caches.open(SHELL).then(cache => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== SHELL && k !== RUNTIME).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).then(response => {
      if (response.ok) { const copy = response.clone(); caches.open(SHELL).then(c => c.put(request, copy)); }
      return response;
    }).catch(async () => (await caches.match(request, { ignoreSearch: true })) || caches.match('index.html')));
    return;
  }
  event.respondWith(caches.match(request).then(hit => hit || fetch(request).then(response => {
    if (response.ok && LAZY.test(url.pathname)) { const copy = response.clone(); caches.open(RUNTIME).then(c => c.put(request, copy)); }
    return response;
  })));
});
`;
}
